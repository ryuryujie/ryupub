    // 공용 팝업 호출
    let popupToken = 0; // 빠르게 다른 팝업을 눌렀을 때 이전 로드 결과가 섞이지 않도록 구분

    function getSrcList(data) {
        return Array.isArray(data.imgs) ? data.imgs : (data.img ? [data.img] : []);
    }

    // 팝업 높이/위치 재계산
    function refreshPopupLayout() {
        if (window.jQuery && jQuery.modal && typeof jQuery.modal.resize === 'function') {
            try { jQuery.modal.resize(); } catch (e) {}
        }
        if (window.jQuery) jQuery(window).trigger('resize');
    }

    // 캐시 방지용 URL (실패 시 재시도에만 사용)
    function bustCache(src) {
        return src + (src.indexOf('?') === -1 ? '?' : '&') + '_r=' + Date.now();
    }

    // 이미지 1장 로드 (실패 시 최대 maxRetry번 재시도)
    function setupImage(imgTag, src, token, onDone, maxRetry) {
        let retry = 0;

        imgTag.onload = function () {
            if (token !== popupToken) return;
            imgTag.style.opacity = '1';
            onDone();
        };
        imgTag.onerror = function () {
            if (token !== popupToken) return;
            if (retry < maxRetry) {
                retry++;
                setTimeout(function () {
                    if (token !== popupToken) return;
                    imgTag.src = bustCache(src); // 브라우저 캐시/404 캐시 우회
                }, 400 * retry);
            } else {
                imgTag.style.display = 'none'; // 끝내 실패하면 깨진 이미지 숨김
                onDone();
            }
        };

        imgTag.style.opacity = '0';
        imgTag.style.transition = 'opacity .25s';
        imgTag.src = src;
        if (imgTag.complete && imgTag.naturalWidth > 0) imgTag.onload(); // 캐시된 경우
    }

    function openProjectPopup(key) {
        const data = projectImages[key];

        if (!data) {
            alert("등록된 상세 이미지가 없습니다.");
            return;
        }

        const srcList = getSrcList(data);
        const token = ++popupToken;

        document.getElementById('modal-title').innerText = data.title;

        const container = document.getElementById('modal-img-container');
        container.innerHTML = ''; // 기존 이미지 초기화

        // 로딩 표시
        const loading = document.createElement('p');
        loading.className = 'pic-loading';
        loading.style.cssText = 'text-align:center;padding:60px 0;color:#888;';
        loading.innerText = '이미지를 불러오는 중입니다...';
        container.appendChild(loading);

        // 순서를 유지하기 위해 img 태그를 먼저 모두 만들어 둠
        let firstLoaded = false;
        srcList.forEach(function (imgSrc, index) {
            const imgTag = document.createElement('img');
            imgTag.alt = data.title + ' 이미지 ' + (index + 1);
            container.appendChild(imgTag);

            setupImage(imgTag, imgSrc, token, function () {
                if (!firstLoaded) {
                    firstLoaded = true;
                    if (loading.parentNode) loading.parentNode.removeChild(loading);
                }
                refreshPopupLayout(); // 이미지가 로드될 때마다 위치/높이 재계산
            }, 2);
        });

        // 기다리지 않고 바로 오픈
        container.scrollTop = 0; // 팝업 내부 스크롤 맨 위에서 시작
        lockPageScroll();
        openModal('#common-popup');
        holdPositionAfterOpen();
        refreshPopupLayout();
    }

    // 팝업이 열려 있는 동안 뒤 배경을 지금 위치 그대로 고정
    let lockTimer = null;
    let pageLocked = false;
    let savedPos = null;

    function getScrollers() {
        return [document.documentElement, document.body, document.getElementById('wrap')].filter(Boolean);
    }
    function inPopup(target) {
        return !!(target && target.nodeType === 1 && target.closest && target.closest('#common-popup'));
    }
    function restorePagePos() {
        if (!savedPos) return;
        if (Math.abs((window.pageYOffset || 0) - savedPos.win) > 1) window.scrollTo(0, savedPos.win);
        getScrollers().forEach(function (el, i) {
            if (Math.abs(el.scrollTop - savedPos.els[i]) > 1) el.scrollTop = savedPos.els[i];
        });
    }
    function onAnyScroll(e) {
        if (inPopup(e.target)) return; // 팝업 내부 스크롤은 허용
        restorePagePos();
    }
    function blockOutsideScroll(e) {
        if (!inPopup(e.target)) e.preventDefault(); // 팝업 밖에서의 휠/터치 스크롤 차단
    }
    function blockScrollKeys(e) {
        const keys = [32, 33, 34, 35, 36, 37, 38, 39, 40]; // space, pgup/dn, end, home, 방향키
        if (keys.indexOf(e.keyCode) === -1) return;
        const t = e.target;
        if (t && /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName)) return;
        if (!inPopup(t)) e.preventDefault();
    }

    function lockPageScroll() {
        if (!pageLocked) {
            pageLocked = true;
            savedPos = {
                win: window.pageYOffset || 0,
                els: getScrollers().map(function (el) { return el.scrollTop; })
            };
            document.addEventListener('scroll', onAnyScroll, true);
            window.addEventListener('scroll', onAnyScroll, true);
            document.addEventListener('wheel', blockOutsideScroll, { passive: false, capture: true });
            document.addEventListener('touchmove', blockOutsideScroll, { passive: false, capture: true });
            document.addEventListener('keydown', blockScrollKeys, true);
        }
        document.documentElement.classList.add('popup-open');
        clearInterval(lockTimer);
        // 닫힘 이벤트가 없는 경우를 대비해 팝업이 사라졌는지 확인
        lockTimer = setInterval(function () {
            const el = document.getElementById('common-popup');
            if (!el || el.offsetParent === null) unlockPageScroll();
        }, 300);
    }
    // 팝업을 여는 순간 다른 스크립트가 맨 위로 보내도 바로 되돌림
    function holdPositionAfterOpen() {
        restorePagePos();
        requestAnimationFrame(restorePagePos);
        setTimeout(restorePagePos, 50);
        setTimeout(restorePagePos, 200);
    }
    function unlockPageScroll() {
        clearInterval(lockTimer);
        if (!pageLocked) return;
        restorePagePos(); // 닫을 때도 열기 전 위치 유지
        pageLocked = false;
        document.documentElement.classList.remove('popup-open');
        document.removeEventListener('scroll', onAnyScroll, true);
        window.removeEventListener('scroll', onAnyScroll, true);
        document.removeEventListener('wheel', blockOutsideScroll, { capture: true });
        document.removeEventListener('touchmove', blockOutsideScroll, { capture: true });
        document.removeEventListener('keydown', blockScrollKeys, true);
        const pos = savedPos;
        // 닫힌 직후 링크 기본동작 등이 맨 위로 보내도 되돌림
        const again = function () {
            if (!pos) return;
            if (Math.abs((window.pageYOffset || 0) - pos.win) > 1) window.scrollTo(0, pos.win);
            getScrollers().forEach(function (el, i) {
                if (Math.abs(el.scrollTop - pos.els[i]) > 1) el.scrollTop = pos.els[i];
            });
        };
        requestAnimationFrame(again);
        setTimeout(again, 50);
        setTimeout(again, 200);
    }
    if (window.jQuery) {
        jQuery(document).on('modal:close modal:after-close', '#common-popup', unlockPageScroll);
        jQuery(document).on('click', '#common-popup a[href="#"], .blocker a[href="#"]', function (e) { e.preventDefault(); });
    }

    // 미리 로드: 마우스를 올리거나 터치하는 순간 이미지를 받아두면 클릭 시 바로 표시됨
    (function () {
        const preloaded = {};
        function preload(key) {
            const data = projectImages[key];
            if (!data || preloaded[key]) return;
            preloaded[key] = true;
            getSrcList(data).forEach(function (src) {
                const img = new Image();
                img.onerror = function () { preloaded[key] = false; }; // 실패하면 다음에 다시 시도
                img.src = src;
            });
        }
        if (!window.jQuery) return;
        jQuery(document).on('mouseover touchstart', '[onclick^="openProjectPopup"]', function () {
            const m = /openProjectPopup\('([^']+)'\)/.exec(this.getAttribute('onclick') || '');
            if (m) preload(m[1]);
        });
    })();
